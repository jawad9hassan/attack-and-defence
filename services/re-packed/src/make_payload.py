#!/usr/bin/env python3
"""
Build-time helper: compresses the compiled `inner` binary with zlib and
emits packed_payload.h, a C header the `stub` binary embeds and
decompresses at runtime. Run once during the Docker image build, after
`inner` has been compiled and before `stub` is compiled.
"""
import sys
import zlib

inner_path, header_path = sys.argv[1], sys.argv[2]

with open(inner_path, "rb") as f:
    raw = f.read()

compressed = zlib.compress(raw, level=9)

with open(header_path, "w") as f:
    f.write("/* Auto-generated by make_payload.py -- do not edit by hand. */\n")
    f.write(f"#define UNPACKED_LEN {len(raw)}\n")
    f.write(f"#define PACKED_LEN {len(compressed)}\n")
    f.write("static const unsigned char PACKED_DATA[PACKED_LEN] = {\n")
    for i in range(0, len(compressed), 16):
        chunk = compressed[i:i + 16]
        f.write(",".join(str(b) for b in chunk) + ",\n")
    f.write("};\n")

print(f"packed {len(raw)} bytes -> {len(compressed)} bytes into {header_path}")
